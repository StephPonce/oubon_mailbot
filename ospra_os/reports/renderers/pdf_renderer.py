"""
PDF Renderer for Business Reports

Uses ReportLab to generate professional PDF reports with:
- Custom branding (logo, colors, company name)
- Headers and footers
- Tables and charts
- Multi-page layout
- Professional typography
"""
from reportlab.lib import colors
from reportlab.lib.pagesizes import letter, A4
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.units import inch
from reportlab.platypus import (
    SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle,
    PageBreak, Image, KeepTogether
)
from reportlab.platypus.flowables import HRFlowable
from reportlab.lib.enums import TA_CENTER, TA_RIGHT, TA_LEFT, TA_JUSTIFY
from datetime import datetime, timezone
from typing import Dict, List, Any, Optional
import io
import logging

logger = logging.getLogger(__name__)


class PDFRenderer:
    """Renders business reports as professional PDF documents"""

    def __init__(self, branding: Optional[Dict] = None):
        """
        Initialize PDF renderer with branding configuration

        Args:
            branding: Branding config with company_name, logo_url, colors, footer_text
        """
        self.branding = branding or self._get_default_branding()
        self.styles = getSampleStyleSheet()
        self._setup_custom_styles()

    def render(self, report_data: Dict) -> bytes:
        """
        Render report data as PDF

        Args:
            report_data: Complete report data structure from ReportEngine

        Returns:
            PDF file as bytes
        """
        logger.info(f"[FILE] Rendering PDF: {report_data['metadata']['report_name']}")

        # Create PDF in memory
        buffer = io.BytesIO()

        # Create document with letter size (8.5" x 11")
        doc = SimpleDocTemplate(
            buffer,
            pagesize=letter,
            rightMargin=0.75*inch,
            leftMargin=0.75*inch,
            topMargin=1*inch,
            bottomMargin=1*inch,
            title=report_data['metadata']['report_name']
        )

        # Build content
        story = []

        # Add cover page
        story.extend(self._render_cover_page(report_data))
        story.append(PageBreak())

        # Add sections
        sections = report_data.get('sections', {})

        if 'executive_summary' in sections:
            story.extend(self._render_executive_summary(sections['executive_summary']))
            story.append(PageBreak())

        if 'revenue' in sections:
            story.extend(self._render_revenue_section(sections['revenue']))
            story.append(PageBreak())

        if 'profit_loss' in sections:
            story.extend(self._render_pnl_section(sections['profit_loss']))
            story.append(PageBreak())

        if 'products' in sections:
            story.extend(self._render_products_section(sections['products']))
            story.append(PageBreak())

        if 'ads' in sections:
            story.extend(self._render_ads_section(sections['ads']))
            story.append(PageBreak())

        # Build PDF
        doc.build(
            story,
            onFirstPage=self._add_page_decorations,
            onLaterPages=self._add_page_decorations
        )

        # Get PDF bytes
        pdf_bytes = buffer.getvalue()
        buffer.close()

        logger.info(f"[SUCCESS] PDF rendered: {len(pdf_bytes) / 1024:.1f} KB")
        return pdf_bytes

    # ==================== Page Decorations ====================

    def _add_page_decorations(self, canvas, doc):
        """Add header and footer to each page"""
        canvas.saveState()

        # Header
        canvas.setFont('Helvetica-Bold', 10)
        canvas.setFillColor(colors.HexColor(self.branding['primary_color']))
        canvas.drawString(
            0.75*inch,
            doc.height + 1.5*inch,
            self.branding['company_name']
        )

        # Footer
        canvas.setFont('Helvetica', 8)
        canvas.setFillColor(colors.grey)
        canvas.drawCentredString(
            doc.width / 2 + 0.75*inch,
            0.5*inch,
            self.branding.get('footer_text', 'Generated by Ospra Intelligence')
        )

        # Page number
        canvas.drawRightString(
            doc.width + 0.75*inch,
            0.5*inch,
            f"Page {doc.page}"
        )

        canvas.restoreState()

    # ==================== Cover Page ====================

    def _render_cover_page(self, report_data: Dict) -> List:
        """Render report cover page"""
        elements = []
        metadata = report_data['metadata']

        # Add spacing from top
        elements.append(Spacer(1, 2*inch))

        # Report title
        title = Paragraph(
            metadata['report_name'],
            self.styles['CustomTitle']
        )
        elements.append(title)
        elements.append(Spacer(1, 0.3*inch))

        # Company name
        company = Paragraph(
            self.branding['company_name'],
            self.styles['CustomSubtitle']
        )
        elements.append(company)
        elements.append(Spacer(1, 0.5*inch))

        # Date range
        date_range = report_data['metadata'].get('date_range', {})
        date_text = self._format_date_range(date_range)

        date_para = Paragraph(
            f"<b>Period:</b> {date_text}",
            self.styles['CustomNormal']
        )
        elements.append(date_para)
        elements.append(Spacer(1, 0.2*inch))

        # Generated date
        generated_para = Paragraph(
            f"<b>Generated:</b> {datetime.now(timezone.utc).strftime('%B %d, %Y at %I:%M %p UTC')}",
            self.styles['CustomNormal']
        )
        elements.append(generated_para)

        return elements

    # ==================== Executive Summary ====================

    def _render_executive_summary(self, data: Dict) -> List:
        """Render executive summary section"""
        elements = []

        # Section title
        elements.append(Paragraph("Executive Summary", self.styles['CustomHeading1']))
        elements.append(Spacer(1, 0.3*inch))

        # Key Metrics Table
        elements.append(Paragraph("Key Metrics", self.styles['CustomHeading2']))
        elements.append(Spacer(1, 0.2*inch))

        metrics = data['key_metrics']

        # Create metrics table
        table_data = [
            ['Metric', 'Current', 'Previous', 'Change'],
            [
                'Revenue',
                f"${metrics['revenue']['value']:,.2f}",
                f"${metrics['revenue']['previous']:,.2f}",
                self._format_change(metrics['revenue']['change_percent'])
            ],
            [
                'Orders',
                f"{metrics['orders']['value']:,}",
                f"{metrics['orders']['previous']:,}",
                self._format_change(metrics['orders']['change_percent'])
            ],
            [
                'Profit',
                f"${metrics['profit']['value']:,.2f}",
                f"{metrics['profit']['margin_percent']:.1f}% margin",
                self._format_change(metrics['profit']['change_percent'])
            ],
            [
                'ROI / ROAS',
                f"{metrics['roi']['value']:.2f}x / {metrics['roi']['roas']:.2f}x",
                '-',
                '-'
            ]
        ]

        table = Table(table_data, colWidths=[2*inch, 1.5*inch, 1.5*inch, 1.5*inch])
        table.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor(self.branding['primary_color'])),
            ('TEXTCOLOR', (0, 0), (-1, 0), colors.whitesmoke),
            ('ALIGN', (0, 0), (-1, -1), 'LEFT'),
            ('FONTNAME', (0, 0), (-1, 0), 'Helvetica-Bold'),
            ('FONTSIZE', (0, 0), (-1, 0), 10),
            ('BOTTOMPADDING', (0, 0), (-1, 0), 12),
            ('BACKGROUND', (0, 1), (-1, -1), colors.beige),
            ('GRID', (0, 0), (-1, -1), 1, colors.black),
            ('FONTNAME', (0, 1), (-1, -1), 'Helvetica'),
            ('FONTSIZE', (0, 1), (-1, -1), 9),
            ('TOPPADDING', (0, 1), (-1, -1), 8),
            ('BOTTOMPADDING', (0, 1), (-1, -1), 8),
        ]))

        elements.append(table)
        elements.append(Spacer(1, 0.4*inch))

        # Highlights
        if data.get('highlights'):
            elements.append(Paragraph("Highlights", self.styles['CustomHeading2']))
            elements.append(Spacer(1, 0.1*inch))

            for highlight in data['highlights']:
                bullet = Paragraph(f"• {highlight}", self.styles['CustomBullet'])
                elements.append(bullet)
                elements.append(Spacer(1, 0.05*inch))

            elements.append(Spacer(1, 0.2*inch))

        # Concerns
        if data.get('concerns'):
            elements.append(Paragraph("Areas of Concern", self.styles['CustomHeading2']))
            elements.append(Spacer(1, 0.1*inch))

            for concern in data['concerns']:
                bullet = Paragraph(f"[WARNING] {concern}", self.styles['CustomBullet'])
                elements.append(bullet)
                elements.append(Spacer(1, 0.05*inch))

            elements.append(Spacer(1, 0.2*inch))

        # Recommendations
        if data.get('recommendations'):
            elements.append(Paragraph("Recommendations", self.styles['CustomHeading2']))
            elements.append(Spacer(1, 0.1*inch))

            for rec in data['recommendations']:
                bullet = Paragraph(f"→ {rec}", self.styles['CustomBullet'])
                elements.append(bullet)
                elements.append(Spacer(1, 0.05*inch))

        return elements

