    # ==================== Helper Methods ====================

    def _setup_custom_styles(self):
        """Setup custom paragraph styles"""

        # Title style
        self.styles.add(ParagraphStyle(
            name='CustomTitle',
            parent=self.styles['Heading1'],
            fontSize=32,
            textColor=colors.HexColor(self.branding['primary_color']),
            spaceAfter=30,
            alignment=TA_CENTER,
            fontName='Helvetica-Bold'
        ))

        # Subtitle style
        self.styles.add(ParagraphStyle(
            name='CustomSubtitle',
            parent=self.styles['Normal'],
            fontSize=18,
            textColor=colors.HexColor(self.branding['secondary_color']),
            spaceAfter=12,
            alignment=TA_CENTER,
            fontName='Helvetica'
        ))

        # Heading 1
        self.styles.add(ParagraphStyle(
            name='CustomHeading1',
            parent=self.styles['Heading1'],
            fontSize=20,
            textColor=colors.HexColor(self.branding['primary_color']),
            spaceAfter=12,
            spaceBefore=12,
            fontName='Helvetica-Bold'
        ))

        # Heading 2
        self.styles.add(ParagraphStyle(
            name='CustomHeading2',
            parent=self.styles['Heading2'],
            fontSize=14,
            textColor=colors.HexColor(self.branding['secondary_color']),
            spaceAfter=6,
            fontName='Helvetica-Bold'
        ))

        # Normal text
        self.styles.add(ParagraphStyle(
            name='CustomNormal',
            parent=self.styles['Normal'],
            fontSize=11,
            leading=14,
            alignment=TA_LEFT
        ))

        # Bullet points
        self.styles.add(ParagraphStyle(
            name='CustomBullet',
            parent=self.styles['Normal'],
            fontSize=10,
            leading=13,
            leftIndent=20,
            spaceBefore=3,
            spaceAfter=3
        ))

    def _format_change(self, change_percent: float) -> str:
        """Format percentage change with color indicator"""
        if change_percent > 0:
            return f"+{change_percent:.1f}%"
        elif change_percent < 0:
            return f"{change_percent:.1f}%"
        else:
            return "0.0%"

    def _format_date_range(self, date_range: Dict) -> str:
        """Format date range for display"""
        if date_range.get('type') == 'relative':
            value = date_range.get('value', 'last_7_days')
            return value.replace('_', ' ').title()
        else:
            start = date_range.get('start', 'N/A')
            end = date_range.get('end', 'N/A')
            return f"{start} to {end}"

    def _get_default_branding(self) -> Dict:
        """Get default branding configuration"""
        return {
            'company_name': 'Oubon Shop',
            'primary_color': '#3b82f6',
            'secondary_color': '#10b981',
            'footer_text': 'Generated by Ospra Intelligence'
        }


